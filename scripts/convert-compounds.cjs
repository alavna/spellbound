#!/usr/bin/env node

/**
 * Compounds Converter
 * Converts LanguageTool's compounds.txt to Spellbound grammar rules
 * These catch split compound words that should be joined
 */

const fs = require('fs');
const path = require('path');

const LT_BASE = path.join(
  __dirname,
  '../.temp/languagetool/languagetool-language-modules/en/src/main/resources/org/languagetool/resource/en'
);
const OUTPUT_DIR = path.join(__dirname, '../packages/core/src/rules/imported/compounds');

function sanitizeId(str) {
  return str
    .replace(/[^a-zA-Z0-9]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '');
}

function escapeRegex(str) {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function parseCompoundLine(line) {
  const trimmed = line.trim();

  // Skip comments and empty lines
  if (!trimmed || trimmed.startsWith('#')) return null;

  // Check for modifiers at end of line
  const plusEnds = trimmed.endsWith('+');
  const starEnds = trimmed.endsWith('*');
  const questionEnds = trimmed.endsWith('?');
  const dollarEnds = trimmed.endsWith('$');

  // Remove modifiers
  let word = trimmed.replace(/[+*?$]+$/, '').trim();

  // Skip if no hyphen
  if (!word.includes('-')) return null;

  // Skip digit patterns for now
  if (word.includes('\\d')) return null;

  // Split on hyphen
  const parts = word.split('-');
  if (parts.length < 2) return null;

  // Both joined and hyphenated are valid (+ modifier)
  const allowJoined = plusEnds;
  const onlyHyphenated = starEnds;

  return {
    original: word,
    parts: parts,
    hyphenated: word,
    joined: parts.join(''),
    spaced: parts.join(' '),
    allowJoined,
    onlyHyphenated,
  };
}

function createCompoundRule(compound, index) {
  const { parts, hyphenated, joined, spaced, allowJoined, onlyHyphenated } = compound;

  // Skip words with apostrophes - they cause parsing issues
  if (joined.includes("'") || hyphenated.includes("'") || spaced.includes("'")) {
    return null;
  }

  const id = `compound_${sanitizeId(joined)}_${index}`;

  // Create pattern to match the spaced version
  const spacedPattern = parts.map((p) => escapeRegex(p)).join('\\\\s+');

  let suggestions;
  if (allowJoined) {
    // Both joined and hyphenated are good
    suggestions = `['${joined}', '${hyphenated}']`;
  } else if (onlyHyphenated) {
    suggestions = `['${hyphenated}']`;
  } else {
    // Default: prefer joined
    suggestions = `['${joined}']`;
  }

  const message = `"${spaced}" should be written as "${allowJoined ? joined : hyphenated}".`;

  return `
  {
    id: '${id}',
    name: '${joined} compound',
    description: 'Compound word: ${hyphenated}',
    category: 'compounds',
    severity: 'suggestion' as const,
    pattern: /\\\\b${spacedPattern}\\\\b/gi,
    message: '${message.replace(/'/g, "\\'")}',
    suggestions: () => ${suggestions},
  }`;
}

async function processCompounds() {
  console.log('📖 Processing LanguageTool compounds...\n');

  // Ensure output directory exists
  if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  const filepath = path.join(LT_BASE, 'compounds.txt');

  if (!fs.existsSync(filepath)) {
    console.log('❌ compounds.txt not found');
    return 0;
  }

  console.log('📄 Processing compounds.txt...');

  const content = fs.readFileSync(filepath, 'utf8');
  const lines = content.split('\n');

  const compounds = [];
  const seen = new Set();

  for (const line of lines) {
    const compound = parseCompoundLine(line);
    if (compound && !seen.has(compound.joined.toLowerCase())) {
      seen.add(compound.joined.toLowerCase());
      compounds.push(compound);
    }
  }

  console.log(`   Found ${compounds.length} compound rules`);

  // Group by first letter
  const grouped = {};
  for (let i = 0; i < compounds.length; i++) {
    const compound = compounds[i];
    const firstLetter = compound.parts[0][0].toLowerCase();
    const group = firstLetter.match(/[a-z]/) ? firstLetter : 'other';

    if (!grouped[group]) {
      grouped[group] = [];
    }
    grouped[group].push({ compound, index: i });
  }

  // Generate files
  const generatedFiles = [];

  for (const [letter, items] of Object.entries(grouped)) {
    const filename = `compounds-${letter}.ts`;
    const filepath = path.join(OUTPUT_DIR, filename);

    const rules = items
      .map(({ compound, index }) => createCompoundRule(compound, index))
      .filter((r) => r !== null);

    const fileContent = `/**
 * Auto-generated compound rules (${letter.toUpperCase()})
 * Source: LanguageTool compounds.txt
 * Generated: ${new Date().toISOString()}
 * 
 * These rules detect split compound words that should be joined.
 * 
 * DO NOT EDIT - Generated by convert-compounds.cjs
 */

import type { GrammarRule } from '../../../types';

export const compoundRules${letter.toUpperCase()}: GrammarRule[] = [${rules.join(',')}
];
`;

    fs.writeFileSync(filepath, fileContent);
    generatedFiles.push({ letter, count: items.length, filename });
    console.log(`   ✅ ${filename}: ${items.length} rules`);
  }

  // Generate index file
  const indexContent = `/**
 * Auto-generated index for compound rules
 * Source: LanguageTool compounds.txt
 * Generated: ${new Date().toISOString()}
 * 
 * Total rules: ${compounds.length}
 */

${generatedFiles.map((f) => `import { compoundRules${f.letter.toUpperCase()} } from './compounds-${f.letter}';`).join('\n')}

import type { GrammarRule } from '../../../types';

export const compoundRules: GrammarRule[] = [
${generatedFiles.map((f) => `  ...compoundRules${f.letter.toUpperCase()},`).join('\n')}
];

export const compoundRuleCount = ${compounds.length};
`;

  fs.writeFileSync(path.join(OUTPUT_DIR, 'index.ts'), indexContent);

  console.log(
    `\n✅ Generated ${generatedFiles.length} files with ${compounds.length} compound rules`
  );
  console.log(`📁 Output: ${OUTPUT_DIR}`);

  return compounds.length;
}

// Run
processCompounds().catch(console.error);
